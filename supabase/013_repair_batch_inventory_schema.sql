-- Recon Water batch inventory schema repair — current deployed schema.
-- Purpose: repair partially-created recon_inventory_* tables IN PLACE without
-- deleting batch data, then recreate the current functions/triggers and refresh
-- the Supabase/PostgREST schema cache.
--
