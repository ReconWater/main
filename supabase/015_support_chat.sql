-- Recon Water support chat
-- Server-mediated anonymous support. Public browser clients never query these tables directly.

create table if not exists public.support_threads (
  id uuid primary key default gen_random_uuid(),
  session_token_hash text not null unique,
  visitor_code text not null,
  email text,
  order_reference text,
  status text not null default 'open' check (status in ('open','closed')),
  customer_last_read_at timestamptz,
  admin_last_read_at timestamptz,
  last_notification_at timestamptz,
  last_message_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  thread_id uuid not null references public.support_threads(id) on delete cascade,
  sender text not null check (sender in ('visitor','admin')),
  body text not null check (char_length(body) between 1 and 1500),
  admin_user_id uuid,
  created_at timestamptz not null default now()
);

create table if not exists public.support_presence (
  id smallint primary key default 1 check (id = 1),
  admin_user_id uuid,
  is_available boolean not null default true,
  last_seen_at timestamptz,
  updated_at timestamptz not null default now()
);

insert into public.support_presence (id,is_available)
values (1,true)
on conflict (id) do nothing;

create index if not exists support_threads_last_message_idx
  on public.support_threads (last_message_at desc);
create index if not exists support_threads_status_idx
  on public.support_threads (status,last_message_at desc);
create index if not exists support_messages_thread_idx
  on public.support_messages (thread_id,id);
create index if not exists support_messages_created_idx
  on public.support_messages (created_at desc);

alter table public.support_threads enable row level security;
alter table public.support_messages enable row level security;
alter table public.support_presence enable row level security;

-- No anon/authenticated policies are intentionally created. All chat access is
-- mediated by the Netlify support API using the Supabase service role.
